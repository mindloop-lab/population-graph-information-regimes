#!/usr/bin/env python3
"""Build table1_protocols.tex from table1_protocols.tsv (repository-relative).

Usage (from the repository root):
    python manuscript/build_table1.py [--out manuscript/table1_protocols.tex]

The table is static: the TSV is the single source. Six columns, with the evidence scope
carried by text rather than by colour.
"""
from __future__ import annotations

import argparse
import csv
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
TSV = ROOT / "manuscript" / "table1_protocols.tsv"

PREAMBLE = [
    r"% AUTO-GENERATED by manuscript/build_table1.py from manuscript/table1_protocols.tsv",
    r"% Static regime taxonomy (no data dependency). Edit the TSV, not this file.",
    r"\small\setlength{\tabcolsep}{4pt}",
    r"\begin{tabular}{@{}>{\raggedright\arraybackslash}p{0.10\textwidth} "
    r">{\raggedright\arraybackslash}p{0.18\textwidth} "
    r">{\centering\arraybackslash}p{0.16\textwidth} "
    r">{\centering\arraybackslash}p{0.16\textwidth} "
    r">{\raggedright\arraybackslash}p{0.16\textwidth} "
    r">{\raggedright\arraybackslash}p{0.12\textwidth}@{}}",
    r"\toprule",
    r"Regime & Definition & Query nodes in training graph & Other queries at inference & "
    r"Evaluation role & Evidence here \\",
    r"\midrule",
]


def main() -> int:
    ap = argparse.ArgumentParser()
    ap.add_argument("--out", default=str(ROOT / "manuscript" / "table1_protocols.tex"))
    args = ap.parse_args()

    with TSV.open(encoding="utf-8") as fh:
        rows = list(csv.DictReader(fh, delimiter="\t"))
    if len(rows) != 6:
        raise SystemExit(f"ABORT: expected 6 regimes, found {len(rows)}")

    lines = list(PREAMBLE)
    for row in rows:
        cells = [row["regime"], row["definition"], row["query_in_training"],
                 row["other_queries"], row["role"], row["evidence"]]
        if cells[0].startswith(("P0", "P1")):
            cells[0] = r"\textbf{" + cells[0] + "}"
        lines.append(" & ".join(cells) + r" \\")
    lines += [r"\bottomrule", r"\end{tabular}"]

    out = Path(args.out)
    out.write_text("\n".join(lines) + "\n", encoding="utf-8")
    print(f"wrote {out} ({len(rows)} regimes)")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
